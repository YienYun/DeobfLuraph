'use strict';


const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const test = require('node:test');

const ROOT = path.resolve(__dirname, '..', '..');
const GOLDEN_PATH = path.join(__dirname, 'golden.json');
const MANIFEST_PATH = path.join(ROOT, 'dev', 'fixtures', 'manifest.json');
const INPUT = path.join(ROOT, 'dev', 'fixtures', 'input');

const golden = fs.existsSync(GOLDEN_PATH) ? JSON.parse(fs.readFileSync(GOLDEN_PATH, 'utf8')) : null;
const manifest = JSON.parse(fs.readFileSync(MANIFEST_PATH, 'utf8'));
const byId = new Map(manifest.samples.map((s) => [s.id, s]));

const INTERNAL_LEAK_RE = /object at 0x[0-9a-f]+|LTable#\d{6,}/i;

function runCli(input, outPath, reportPath, args) {
  const r = spawnSync(process.execPath, [
    path.join(ROOT, 'deob.js'), input, '-o', outPath, '--report', reportPath, ...args,
  ], { cwd: ROOT, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, timeout: 20 * 60 * 1000 });
  return {
    status: r.status,
    stdout: r.stdout || '',
    stderr: r.stderr || '',
    output: fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : null,
    report: fs.existsSync(reportPath) ? JSON.parse(fs.readFileSync(reportPath, 'utf8')) : null,
  };
}

function md5(text) {
  return crypto.createHash('md5').update(text, 'utf8').digest('hex');
}

test('golden.json is present and describes this manifest', (t) => {
  if (!golden) {
    t.skip('test/golden.json is missing; run: node dev/scripts/update-golden.js');
    return;
  }
  assert.equal(golden.schema_version, 1);
  for (const row of golden.samples) {
    assert.ok(byId.has(row.id), `${row.id} is not in fixtures/manifest.json`);
    assert.ok(Array.isArray(row.args) && row.args.length > 0, `${row.id} has no pinned flags`);
  }
});

for (const row of (golden ? golden.samples : [])) {
  test(`e2e ${row.id}`, (t) => {
    const sample = byId.get(row.id);
    const input = path.join(INPUT, sample.file);
    if (!fs.existsSync(input)) {
      t.skip(`fixture ${sample.file} is missing; run: node dev/scripts/fixtures.js fetch --tier ${sample.tier}`);
      return;
    }

    const dir = fs.mkdtempSync(path.join(os.tmpdir(), `deobf-e2e-${row.id}-`));
    try {
      const first = runCli(input, path.join(dir, 'a.luau'), path.join(dir, 'a.json'), row.args);

      if (row.expected_error) {
        assert.notEqual(first.status, 0, 'this sample is expected to be refused, not lifted');
        assert.match(first.stderr, /no v14 dispatch loop|not lifted/i);
        return;
      }

      assert.equal(first.status, 0, first.stderr.slice(0, 800));
      assert.ok(first.output, 'no output file was written');
      assert.ok(first.report, 'no report was written');

      assert.equal(first.report.result_type, row.result_type, 'result type changed');
      assert.equal(first.report.output_sha256, row.sha256, 'output sha256 changed');
      assert.equal(md5(first.output), row.md5, 'output md5 changed');
      assert.equal(first.output.split('\n').length - 1, row.lines, 'line count changed');
      if (row.functions !== null && row.functions !== undefined) {
        assert.equal(first.report.lift_stats.functions, row.functions, 'lifted function count changed');
      }

      const digest = crypto.createHash('sha256').update(first.output, 'utf8').digest('hex');
      assert.equal(digest, first.report.output_sha256);
      assert.equal(Buffer.byteLength(first.output, 'utf8'), first.report.output_bytes);

      const lines = first.output.split('\n');
      assert.match(lines[0], /^-- This Source Was Generated by /);
      assert.equal(first.output.split('Deobf By Zed').length - 1, 1);

      assert.ok(!INTERNAL_LEAK_RE.test(first.output), 'output leaks an internal object identity');

      if (row.result_type === 'devirtualized') {
        const { isValidLuaSyntax } = require('../../node/luau_check');
        assert.ok(isValidLuaSyntax(first.output), 'output is not valid Luau');
      } else {
        assert.match(first.output, /BEHAVIOUR TRACE, NOT RECONSTRUCTED SOURCE/);
      }

      const second = runCli(input, path.join(dir, 'b.luau'), path.join(dir, 'b.json'), row.args);
      assert.equal(second.status, 0, second.stderr.slice(0, 800));
      assert.equal(second.output, first.output, 'two runs over one input produced different bytes');
      assert.equal(second.report.output_sha256, first.report.output_sha256);
    } finally {
      fs.rmSync(dir, { recursive: true, force: true });
    }
  });
}

test('an input nothing recognises is labelled as a trace, not as source', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'deobf-generic-'));
  try {
    const input = path.join(dir, 'plain.lua');
    fs.writeFileSync(input, 'local x = 1\nprint(x)\n');
    const res = runCli(input, path.join(dir, 'out.lua'), path.join(dir, 'out.json'), ['--budget', '10']);
    assert.equal(res.status, 0, res.stderr);
    assert.equal(res.report.result_type, 'trace');
    assert.match(res.output, /BEHAVIOUR TRACE, NOT RECONSTRUCTED SOURCE/);
    assert.ok(res.report.warnings.some((w) => /does not match any obfuscator/.test(w)), JSON.stringify(res.report.warnings));
    assert.ok(res.report.warnings.some((w) => /behaviour trace, not reconstructed source/.test(w)));
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

test('a trace is deterministic too, and carries no machine paths', (t) => {
  const sample = byId.get('t15-0-392628');
  const input = path.join(INPUT, sample.file);
  if (!fs.existsSync(input)) {
    t.skip(`fixture ${sample.file} is missing; run: node dev/scripts/fixtures.js fetch --only ${sample.id}`);
    return;
  }
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'deobf-trace-'));
  try {
    const args = ['--budget', '20', '--timeout', '45'];
    const first = runCli(input, path.join(dir, 'a.luau'), path.join(dir, 'a.json'), args);
    const second = runCli(input, path.join(dir, 'b.luau'), path.join(dir, 'b.json'), args);
    assert.equal(first.status, 0, first.stderr);
    assert.equal(first.report.result_type, 'trace');
    assert.match(first.output, /^-- This Source Was Generated by /);
    assert.match(first.output, /BEHAVIOUR TRACE, NOT RECONSTRUCTED SOURCE/);
    assert.ok(!/deobf_node_[A-Za-z0-9]+/.test(first.output), 'trace leaks the temp directory');
    assert.ok(!/\/(?:tmp|var)\//.test(first.output), 'trace leaks an absolute path');
    assert.equal(second.output, first.output, 'two trace runs produced different bytes');
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});
