'use strict';

const WATERMARK_COMMENT = '-- This Source Was Generated by discord.gg/c3xVMnUUBv';
const WATERMARK_PRINT = 'print("Deobf By Zed")';
// a formatter (stylua) may rewrite the call with single quotes or spaces, so
// look for the call itself rather than the exact text written here
const WATERMARK_PRINT_RE = /print\s*\(\s*(['"])Deobf By Zed\1\s*\)/;

const STMT_START_RE = /^(?:local\b|function\b|if\b|for\b|while\b|repeat\b|do\b|pcall\b|xpcall\b|task\.|spawn\b|warn\b|print\b|game\b|[A-Za-z_][A-Za-z0-9_.:]*\s*(?:=|\(|:|"))/;

/**
 * Match a Lua long bracket `[=*[` at `pos` in `src`.
 * Returns the number of `=` signs (>= 0), or -1 if `src[pos]` is not a long bracket.
 */
function matchLongBracketOpen(src, pos) {
  if (src[pos] !== '[') return -1;
  let i = pos + 1;
  while (i < src.length && src[i] === '=') i++;
  if (i < src.length && src[i] === '[') return i - pos - 1;
  return -1;
}

/**
 * Scan Lua/Luau source line-by-line while tracking strings, long brackets,
 * comments,括号/table depth, and top-level block depth so watermark insertion
 * never lands inside a string/comment or after a trailing top-level `return`.
 */
function analyzeLuaLines(code) {
  const n = code.length;
  let state = 'normal'; // 'normal' | 'str' | 'line_comment' | 'long_str' | 'long_comment'
  let strQuote = '';
  let longEq = 0;
  let blockDepth = 0;
  let bracketDepth = 0;
  let prevSigChar = '';

  const lineMeta = [{
    startOffset: 0,
    safeLineStart: true,
    blockDepth: 0,
    bracketDepth: 0,
    topLevelReturn: false,
    topLevelReturnOffset: -1,
  }];
  let curLine = 0;
  let i = 0;

  const advanceNewline = (nextOffset, safe) => {
    curLine++;
    lineMeta.push({
      startOffset: nextOffset,
      safeLineStart: safe,
      blockDepth,
      bracketDepth,
      topLevelReturn: false,
      topLevelReturnOffset: -1,
    });
  };

  while (i < n) {
    const ch = code[i];

    if (state === 'line_comment') {
      if (ch === '\n') {
        state = 'normal';
        advanceNewline(i + 1, bracketDepth === 0);
      }
      i++;
      continue;
    }

    if (state === 'str') {
      if (ch === '\\') {
        if (i + 1 < n && code[i + 1] === '\n') {
          advanceNewline(i + 2, false);
          i += 2;
          continue;
        }
        if (i + 2 < n && code[i + 1] === '\r' && code[i + 2] === '\n') {
          advanceNewline(i + 3, false);
          i += 3;
          continue;
        }
        i += 2;
        continue;
      }
      if (ch === strQuote) {
        state = 'normal';
        prevSigChar = ch;
        i++;
        continue;
      }
      if (ch === '\n') {
        state = 'normal';
        advanceNewline(i + 1, bracketDepth === 0);
      }
      i++;
      continue;
    }

    if (state === 'long_str' || state === 'long_comment') {
      if (ch === ']') {
        let j = i + 1;
        let eq = 0;
        while (j < n && code[j] === '=') { eq++; j++; }
        if (eq === longEq && j < n && code[j] === ']') {
          if (state === 'long_str') prevSigChar = ']';
          state = 'normal';
          i = j + 1;
          continue;
        }
      }
      if (ch === '\n') {
        advanceNewline(i + 1, false);
      }
      i++;
      continue;
    }

    // state === 'normal'
    if (ch === '\n') {
      advanceNewline(i + 1, bracketDepth === 0);
      i++;
      continue;
    }

    if (ch === '-' && code[i + 1] === '-') {
      const lb = matchLongBracketOpen(code, i + 2);
      if (lb >= 0) {
        state = 'long_comment';
        longEq = lb;
        i = i + 4 + lb;
      } else {
        state = 'line_comment';
        i += 2;
      }
      continue;
    }

    if (ch === '"' || ch === "'" || ch === '`') {
      state = 'str';
      strQuote = ch;
      i++;
      continue;
    }

    if (ch === '[') {
      const lb = matchLongBracketOpen(code, i);
      if (lb >= 0) {
        state = 'long_str';
        longEq = lb;
        i = i + 2 + lb;
        continue;
      }
      bracketDepth++;
      prevSigChar = ch;
      i++;
      continue;
    }

    if (ch === '(' || ch === '{') {
      bracketDepth++;
      prevSigChar = ch;
      i++;
      continue;
    }

    if (ch === ')' || ch === '}' || ch === ']') {
      bracketDepth = Math.max(0, bracketDepth - 1);
      prevSigChar = ch;
      i++;
      continue;
    }

    if (/[A-Za-z_]/.test(ch)) {
      let j = i + 1;
      while (j < n && /[A-Za-z0-9_]/.test(code[j])) j++;
      const word = code.slice(i, j);
      const isField = prevSigChar === '.' || prevSigChar === ':';
      if (!isField) {
        if (word === 'return' && blockDepth === 0 && bracketDepth === 0) {
          lineMeta[curLine].topLevelReturn = true;
          lineMeta[curLine].topLevelReturnOffset = i;
        } else if (word === 'function' || word === 'if' || word === 'do' || word === 'repeat') {
          blockDepth++;
        } else if (word === 'end' || word === 'until') {
          blockDepth = Math.max(0, blockDepth - 1);
        }
      }
      prevSigChar = word[word.length - 1];
      i = j;
      continue;
    }

    if (!/\s/.test(ch)) {
      prevSigChar = ch;
    }
    i++;
  }

  return lineMeta;
}

/**
 * Inject post-deobfuscation attribution into Lua/Luau source code:
 *   1. `-- This Source Was Generated by discord.gg/c3xVMnUUBv` at a random safe
 *      statement boundary.
 *   2. `print("Deobf By Zed")` once at the bottom of the script (or right before
 *      any trailing top-level `return` statement so module syntax stays 100% valid).
 */
function injectWatermark(source, opts = {}) {
  if (typeof source !== 'string') return source;
  const rng = typeof opts.rng === 'function' ? opts.rng : Math.random;

  let normalized = source.replace(/\r\n/g, '\n');
  const hasComment = normalized.includes(WATERMARK_COMMENT);
  const hasPrint = WATERMARK_PRINT_RE.test(normalized);
  if (hasComment && hasPrint) return normalized;

  const lines = normalized.split('\n');
  if (lines.length > 0 && lines[lines.length - 1] === '') {
    lines.pop();
  }

  // Step 1: Insert `print("Deobf By Zed")` at bottom (or right before final top-level `return`)
  if (!hasPrint) {
    const joined = lines.join('\n');
    const metaForPrint = analyzeLuaLines(joined);
    let lastTopReturnIdx = -1;
    for (let idx = 0; idx < metaForPrint.length && idx < lines.length; idx++) {
      if (metaForPrint[idx].topLevelReturn) {
        lastTopReturnIdx = idx;
      }
    }
    if (lastTopReturnIdx >= 0) {
      const m = metaForPrint[lastTopReturnIdx];
      if (m.safeLineStart && /^[ \t]*return\b/.test(lines[lastTopReturnIdx])) {
        const indentMatch = lines[lastTopReturnIdx].match(/^([ \t]*)/);
        const indent = indentMatch ? indentMatch[1] : '';
        lines.splice(lastTopReturnIdx, 0, `${indent}${WATERMARK_PRINT}`);
      } else {
        const patched =
          joined.slice(0, m.topLevelReturnOffset) +
          `${WATERMARK_PRINT}; ` +
          joined.slice(m.topLevelReturnOffset);
        lines.splice(0, lines.length, ...patched.split('\n'));
      }
    } else {
      lines.push(WATERMARK_PRINT);
    }
  }

  // Step 2: Insert `-- This Source Was Generated by discord.gg/c3xVMnUUBv` at a random safe line
  if (!hasComment) {
    const meta = analyzeLuaLines(lines.join('\n'));
    const preferred = [];
    const fallback = [];

    for (let idx = 0; idx < lines.length; idx++) {
      if (idx === 0 && lines[0].startsWith('#!')) continue;
      const m = meta[idx];
      if (!m || !m.safeLineStart) continue;
      const trimmed = lines[idx].trim();
      if (!trimmed) continue;
      if (trimmed === WATERMARK_PRINT) continue;
      fallback.push(idx);
      if (STMT_START_RE.test(trimmed)) {
        preferred.push(idx);
      }
    }

    const pool = preferred.length > 0 ? preferred : fallback;
    if (pool.length > 0) {
      const pick = pool[Math.min(pool.length - 1, Math.floor(rng() * pool.length))];
      const indentMatch = lines[pick].match(/^([ \t]*)/);
      const indent = indentMatch ? indentMatch[1] : '';
      lines.splice(pick, 0, `${indent}${WATERMARK_COMMENT}`);
    } else {
      lines.unshift(WATERMARK_COMMENT);
    }
  }

  return lines.join('\n') + '\n';
}

module.exports = {
  WATERMARK_COMMENT,
  WATERMARK_PRINT,
  analyzeLuaLines,
  injectWatermark,
};
