test('multi-obfuscator detector classifies MoonSec, MoonVeil, Prometheus, PSU, IronBrew, Hercules, LuaObfuscator and more', () => {
  const cases = [
    ['-- This file was protected using Luraph Obfuscator v15.1 [https://lura.ph/]', 'luraph_v15'],
    ['-- This file was protected using Luraph Obfuscator v14.7 [https://lura.ph/]', 'luraph_v14'],
    ['-- This file was protected using Luraph Obfuscator v14.8 [https://lura.ph/]', 'luraph_v14'],
    ['-- This file was protected using Luraph Obfuscator v14.9 [https://lura.ph/]', 'luraph_v14'],
    ['-- This file was generated using Luraph Obfuscator v14.4', 'generic'],
    ['--[[ This file was protected with MoonSec V3 ]] return(function() end)()', 'moonsec'],
    ['-- ..:::MoonSec::.. V2', 'moonsec'],
    ['-- This script was generated using MoonVeil 2.0.26 [https://moonveil.cc]', 'moonveil'],
    ['return({{},function(p,g)return function(k,d)local i=0b10100110 end end})', 'moonveil'],
    ['-- Obfuscated using Prometheus Obfuscator', 'prometheus'],
    ['return(function(...)local w={"\\069\\066\\081","\\104\\101\\108\\108\\111"} end)()', 'prometheus'],
    ['-- Protected by PSU Obfuscator v4.5', 'psu'],
    ['local x = "PSU|102938102938"', 'psu'],
    ['-- this file was generated using ironbrew1\nreturn 1', 'ironbrew1'],
    ['--[[ AztupBrew(Fork of IronBrew2): obfuscation; Version 2.7.2 ]]', 'ironbrew2'],
    ['local p=getfenv or function()return _ENV end;local a=string.byte;local b=setmetatable;', 'ironbrew2'],
    ['-- Obfuscated by Hercules v1.6', 'hercules'],
    ['return WrapState(BcToState("abc"))', 'hercules'],
    ['-- LuaObfuscator.com', 'luaobfuscator'],
    ['local v0=tonumber;local v1=string.byte;local v2=string.char;', 'luaobfuscator'],
    ['-- Protected with Goofyscator', 'goofyscator'],
    ['--[[ Obfuscated using ironveil v1 ]]', 'ironveil'],
    ['-- 77fuscator | 77FUS|abc', 'f77'],
    ['local payload = "XHD:998877"', 'xhider'],
    ['-- herrtt boronide', 'boronide'],
    ['--ironbrew3: payload', 'ironbrew3'],
    ['local SynapseXen_iiiI = 1', 'synapsexen'],
    ['-- wYnFuscate', 'wynfuscate'],
  ];

  for (const [sample, expected] of cases) {
    const got = detect.detect(sample);
    assert.equal(got.plugin.name, expected, `Expected ${expected} for sample: ${sample.slice(0, 60)}`);
    if (expected !== 'generic') {
      assert.ok(got.confidence >= 0.5, `Expected >= 0.5 confidence for ${expected}`);
    }
  }

  assert.equal(detect.byName('luraph_v14_8').name, 'luraph_v14');
  const zlib = require('zlib');
  if (typeof zlib.zstdCompressSync === 'function') {
    const innerMv = '-- This script was generated using MoonVeil 2.1.1 [https://moonveil.cc]\nreturn(function(...)end)(...)';
    const b64 = zlib.zstdCompressSync(Buffer.from(innerMv, 'latin1')).toString('base64');
    const wrapped = `return loadstring(buffer.tostring(game:GetService'EncodingService':DecompressBuffer(buffer.fromstring(base64.decode"${b64}"),Enum.CompressionAlgorithm.Zstd)))(...)`;
    assert.equal(detect.detect(wrapped).plugin.name, 'moonveil');
  }
  assert.equal(detect.byName('moonsec_v3').name, 'moonsec');
  assert.equal(detect.byName('ib2').name, 'ironbrew2');
});

test('input/ subfolder automatically routes deobfuscated output to sibling output/ folder without auto-rename', t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'deobf-io-split-'));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));

  const inDir = path.join(dir, 'input');
  const outDir = path.join(dir, 'output');
  fs.mkdirSync(inDir, { recursive: true });
  fs.mkdirSync(outDir, { recursive: true });

  const inFile = path.join(inDir, 'hello.lua');
  const reportFile = path.join(dir, 'report.json');
  fs.writeFileSync(inFile, '-- LuaObfuscator.com\nlocal v0 = "Hello Multi Deobf"\nprint(v0)\n', 'utf8');

  const r = spawnSync(process.execPath, [path.join(ROOT, 'deob.js'), inFile, '--report', reportFile], {
    cwd: ROOT,
    encoding: 'utf8',
    timeout: 60000,
  });
  assert.equal(r.status, 0, r.stderr);

  const expectedOut = path.join(outDir, 'hello.lua');
  assert.ok(fs.existsSync(expectedOut), 'expected output inside sibling output/ folder');
  assert.equal(fs.existsSync(path.join(inDir, 'output')), false, 'must not create input/output/ nested folder');

  const outCode = fs.readFileSync(expectedOut, 'utf8');
  assert.match(outCode, /Hello Multi Deobf/);
  assert.ok(outCode.includes('-- This Source Was Generated by discord.gg/c3xVMnUUBv'));
  assert.ok(outCode.includes('print("Deobf By Zed")'));

  const rep = JSON.parse(fs.readFileSync(reportFile, 'utf8'));
  assert.equal(rep.obfuscator, 'luaobfuscator');
  assert.equal(rep.result_type, 'devirtualized');
  assert.equal(rep.rename_stats, undefined, 'renamer must stay off unless --rename is explicitly passed');

  // Nested per-obfuscator subfolder inside input/ (e.g. input/MoonVeil/sub.lua -> output/MoonVeil/sub.lua)
  const subInDir = path.join(inDir, 'MoonVeil');
  fs.mkdirSync(subInDir, { recursive: true });
  const subInFile = path.join(subInDir, 'nested.lua');
  fs.writeFileSync(subInFile, '-- LuaObfuscator.com\nlocal v0 = "Nested Subfolder OK"\nprint(v0)\n', 'utf8');
  const r2 = spawnSync(process.execPath, [path.join(ROOT, 'deob.js'), subInFile], {
    cwd: ROOT,
    encoding: 'utf8',
    timeout: 60000,
  });
  assert.equal(r2.status, 0, r2.stderr);
  assert.ok(fs.existsSync(path.join(outDir, 'MoonVeil', 'nested.lua')), 'expected mirrored subfolder inside output/');
  assert.equal(fs.existsSync(path.join(subInDir, 'output')), false, 'must not pollute input/MoonVeil/ with output/');
});

test('native Lua 5.1 bytecode compiler + luac32To64 + luadec/decom pipeline recovers Lua source cleanly', t => {
  const lua51c = path.join(ROOT, 'bin', 'lua5.1');
  if (!fs.existsSync(lua51c) || process.platform === 'win32') {
    t.skip('native Linux lua5.1 binary not present');
    return;
  }
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'luac-roundtrip-'));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));

  const dumpScript = path.join(dir, 'make_chunk.lua');
  const chunkPath = path.join(dir, 'sample.luac');
  fs.writeFileSync(
    dumpScript,
    [
      'local function target(a, b)',
      '  return a + b * 3, "DECOMP_OK"',
      'end',
      `local f = assert(io.open(${JSON.stringify(chunkPath)}, "wb"))`,
      'f:write(string.dump(target))',
      'f:close()',
    ].join('\n'),
    'utf8'
  );
  const build = spawnSync(lua51c, [dumpScript], { encoding: 'utf8' });
  assert.equal(build.status, 0, build.stderr);

  const raw = fs.readFileSync(chunkPath);
  const decompiled = decompileLua51Bytecode(luac32To64(raw));
  assert.match(decompiled, /DECOMP_OK/);
});

test('MoonVeil beautifier folds expressions, unboxes upvalue cells, and reconstructs generic for-loops cleanly', () => {
  const py = spawnSync(
    'python3',
    [
      '-c',
      [
        'import sys',
        'sys.path.insert(0, "core/obfuscators/moonveil")',
        'from moonveil.front import parse',
        'from moonveil.beautify import beautify_reconstructed',
        'sample = b"""',
        'local ctx = {}',
        'ctx._ = getfenv()',
        'ctx.h = function(...) return {[1] = {...}, [2] = select("#", ...)} end',
        'ctx.i = (function() local m = table.unpack or unpack; return function(o) return m(o[1], 1, o[2]) end end)()',
        'ctx.g = (function() return function(f, s, c) local mt = getmetatable(f); if mt and mt.__iter then return mt.__iter(f) end; return f, s, c end end)()',
        'ctx.b = function(c, u) return function() u[1].value = u[1].value + u[2].value end end',
        'ctx.a = function(c) return function()',
        '    local a, b, d, e, f',
        '    a = 0',
        '    a = {value = a}',
        '    b = {}',
        '    b[1] = 10',
        '    b[2] = 20',
        '    b[3] = 30',
        '    d = c._.ipairs',
        '    d, e, f = d(b)',
        '    d, e, f = c.g(d, e, f)',
        '    local k, v = d(e, f)',
        '    f = k',
        '    if f == nil then else',
        '        while true do',
        '            v = {value = v}',
        '            local fn = c:b({a, v})',
        '            fn()',
        '            k, v = d(e, f)',
        '            f = k',
        '            if f == nil then break end',
        '        end',
        '    end',
        '    return a.value',
        'end end',
        'return (function(x, ...) return x:a()(...) end)(ctx, ...)',
        '"""',
        'ast = parse(sample)',
        'selected = {}',
        'for s in ast["body"]:',
        '    if s["type"] == "AssignmentStatement":',
        '        selected[s["variables"][0]["identifier"]["name"]] = s["init"][0]',
        'entry = ast["body"][-1]["arguments"][0]["base"]',
        'out = beautify_reconstructed(selected, entry).decode("utf-8")',
        'print(out)',
      ].join('\n'),
    ],
    { cwd: ROOT, encoding: 'utf8', timeout: 15000 }
  );
  assert.equal(py.status, 0, py.stderr);
  assert.doesNotMatch(py.stdout, /\.value\b/);
  assert.doesNotMatch(py.stdout, /__mv_|__w_|__cell_|__moonveil_recovered/);
  assert.match(py.stdout, /for .+ in ipairs\(\{10, 20, 30\}\) do/);

  const luauBin = path.join(ROOT, 'bin', 'luau');
  if (fs.existsSync(luauBin) && process.platform !== 'win32') {
    const tmp = path.join(os.tmpdir(), `mv-beautify-check-${process.pid}.luau`);
    try {
      fs.writeFileSync(tmp, `local function run()\n${py.stdout}\nend\nassert(run() == 60)\nprint("SUM_60_OK")\n`, 'utf8');
      const run = spawnSync(luauBin, [tmp], { encoding: 'utf8' });
      assert.equal(run.status, 0, run.stderr);
      assert.match(run.stdout, /SUM_60_OK/);
    } finally {
      fs.rmSync(tmp, { force: true });
    }
  }

  const rideOut = path.join(ROOT, 'samples', 'output', 'RideAFish_MoonVeil.lua');
  if (fs.existsSync(rideOut)) {
    const src = fs.readFileSync(rideOut, 'utf8');
    assert.doesNotMatch(src, /__moonveil_recovered/);
    assert.doesNotMatch(src, /\.value\b/);
    assert.match(src, /local function startMainHub\(\)/);
    assert.match(src, /for idx, eggName in ipairs\(/);
  }
});

test('post-deobfuscation watermark preserves valid Luau syntax across scripts, return modules, and multiline strings', () => {
  const { WATERMARK_COMMENT, WATERMARK_PRINT, injectWatermark } = require('../src/watermark');
  const luauAst = path.join(ROOT, 'bin', 'luau-ast');
  const hasAst = fs.existsSync(luauAst) && process.platform !== 'win32';

  const samples = [
    [
      'local Players = game:GetService("Players")',
      'local msg = [[',
      'multiline line 1',
      'multiline line 2',
      ']]',
      'if Players then',
      '  print(msg)',
      'end',
    ].join('\n'),
    [
      'local Module = {}',
      'function Module.init(x)',
      '  if x == nil then',
      '    return false',
      '  end',
      '  return true',
      'end',
      'return Module',
    ].join('\n'),
    'return (function(a, b)\n  local sum = a + b\n  return sum\nend)(10, 20)\n',
    'local M = { a = 1 } do M.b = 2 end return M\n',
  ];

  for (const rngVal of [0, 0.35, 0.75, 0.999]) {
    for (const src of samples) {
      const out = injectWatermark(src, { rng: () => rngVal });
      assert.ok(out.includes(WATERMARK_COMMENT), 'expected watermark comment');
      assert.ok(out.includes(WATERMARK_PRINT), 'expected watermark print');
      assert.ok(!out.includes('multiline line 1\n' + WATERMARK_COMMENT), 'must never inject inside [[...]]');
      // Idempotency check
      const twice = injectWatermark(out, { rng: () => rngVal });
      assert.equal(twice.split(WATERMARK_COMMENT).length - 1, 1);
      assert.equal(twice.split(WATERMARK_PRINT).length - 1, 1);

      if (hasAst) {
        const tmp = path.join(os.tmpdir(), `wm-ast-${process.pid}-${Math.random().toString(36).slice(2)}.luau`);
        try {
          fs.writeFileSync(tmp, out, 'utf8');
          const r = spawnSync(luauAst, [tmp], { encoding: 'utf8' });
          assert.equal(r.status, 0, `luau-ast failed on watermarked code:\n${out}\nstderr: ${r.stderr}`);
        } finally {
          fs.rmSync(tmp, { force: true });
        }
      }
    }
  }
});

